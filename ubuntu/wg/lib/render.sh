# shellcheck shell=bash
# Rendering of the wg-quick config from the state and its canonical form for comparison.
#
# The rendered config is self-contained and never calls wg-network, so the interface keeps
# working after the tool is uninstalled.

render_conf() {
    local name key addr addr6 routes endpoint keepalive enabled pending psk comment
    local -a addrs=("${NODE[ADDRESS]}")
    [[ -n ${NODE[ADDRESS6]-} ]] && addrs+=("${NODE[ADDRESS6]}")

    printf '# Generated by wg-network %s. Do not edit: manual changes are detected and\n' "$(wgn_version)"
    printf '# wg-network refuses to overwrite them without --force. Manage with: wg-network -i %s help\n' "$IFACE"
    printf '\n[Interface]\n'
    printf 'Address = %s\n' "$(join_by ', ' "${addrs[@]}")"
    [[ -n ${NODE[LISTEN_PORT]-} ]] && printf 'ListenPort = %s\n' "${NODE[LISTEN_PORT]}"
    printf 'PrivateKey = %s\n' "$(<"$ST_KEY")"
    [[ -n ${NODE[MTU]-} ]] && printf 'MTU = %s\n' "${NODE[MTU]}"
    [[ ${NODE[TABLE]} != auto ]] && printf 'Table = %s\n' "${NODE[TABLE]}"
    render_hooks

    while IFS=$FS read -r name key addr addr6 routes endpoint keepalive enabled pending psk comment; do
        [[ $enabled == 1 && $pending == 0 ]] || continue
        printf '\n# peer: %s%s\n[Peer]\n' "$name" "${comment:+ — $comment}"
        printf 'PublicKey = %s\n' "$key"
        [[ -n $psk ]] && printf 'PresharedKey = %s\n' "$psk"
        printf 'AllowedIPs = %s\n' "$(peer_allowed_ips "$addr" "$addr6" "$routes")"
        [[ -n $endpoint ]] && printf 'Endpoint = %s\n' "$endpoint"
        [[ -n $keepalive && $keepalive != 0 ]] && printf 'PersistentKeepalive = %s\n' "$keepalive"
    done < <(st_peers_tsv)
    return 0
}

# Hub firewall rules as "family|table|chain|match|action". One description yields both PostUp
# (idempotent: -C || -I) and PostDown (-D), so a repeated up never duplicates rules and down
# removes exactly what up added.
hub_firewall_rules() {
    local nat=${NODE[NAT]-} net4
    [[ ${NODE[ROLE]} == hub ]] || return 0
    cidr_network "${NODE[ADDRESS]}" net4

    if [[ ${NODE[FORWARD]} == 1 ]]; then
        echo "4|filter|FORWARD|-i %i -o %i|-j ACCEPT"
        [[ -n ${NODE[ADDRESS6]-} ]] && echo "6|filter|FORWARD|-i %i -o %i|-j ACCEPT"
    fi
    if [[ -n $nat ]]; then
        echo "4|filter|FORWARD|-i %i -o $nat|-j ACCEPT"
        echo "4|filter|FORWARD|-i $nat -o %i -m conntrack --ctstate RELATED,ESTABLISHED|-j ACCEPT"
        echo "4|nat|POSTROUTING|-s $net4 -o $nat|-j MASQUERADE"
        if [[ -n ${NODE[ADDRESS6]-} ]]; then
            local net6
            cidr_network "${NODE[ADDRESS6]}" net6
            echo "6|filter|FORWARD|-i %i -o $nat|-j ACCEPT"
            echo "6|filter|FORWARD|-i $nat -o %i -m conntrack --ctstate RELATED,ESTABLISHED|-j ACCEPT"
            echo "6|nat|POSTROUTING|-s $net6 -o $nat|-j MASQUERADE"
        fi
    fi
    # MSS clamping: without it TCP stalls through the tunnel wherever PMTUD is broken.
    if [[ ${NODE[FORWARD]} == 1 || -n $nat ]]; then
        echo "4|mangle|FORWARD|-o %i -p tcp --tcp-flags SYN,RST SYN|-j TCPMSS --clamp-mss-to-pmtu"
        echo "4|mangle|FORWARD|-i %i -p tcp --tcp-flags SYN,RST SYN|-j TCPMSS --clamp-mss-to-pmtu"
        if [[ -n ${NODE[ADDRESS6]-} ]]; then
            echo "6|mangle|FORWARD|-o %i -p tcp --tcp-flags SYN,RST SYN|-j TCPMSS --clamp-mss-to-pmtu"
            echo "6|mangle|FORWARD|-i %i -p tcp --tcp-flags SYN,RST SYN|-j TCPMSS --clamp-mss-to-pmtu"
        fi
    fi
}

# Hooks never fail the interface: if iptables fails the tunnels stay up and wg-network doctor
# reports the missing rules (fail-open in favour of VPN availability).
render_hooks() {
    local fam table chain match action bin tag='-m comment --comment wg-network'
    local nat=${NODE[NAT]-}
    [[ ${NODE[ROLE]} == hub ]] || return 0

    # Forwarding is enabled per interface, not with the global ip_forward: changing ip_forward
    # resets other IPv4 sysctls (Documentation/networking/ip-sysctl.rst).
    if [[ ${NODE[FORWARD]} == 1 || -n $nat ]]; then
        printf 'PostUp = sysctl -q -w net.ipv4.conf.%%i.forwarding=1 || true\n'
    fi
    [[ -n $nat ]] && printf 'PostUp = sysctl -q -w net.ipv4.conf.%s.forwarding=1 || true\n' "$nat"

    while IFS='|' read -r fam table chain match action; do
        bin=iptables
        [[ $fam == 6 ]] && bin=ip6tables
        printf 'PostUp = %s -w -t %s -C %s %s %s %s 2>/dev/null || %s -w -t %s -I %s %s %s %s || true\n' \
            "$bin" "$table" "$chain" "$match" "$tag" "$action" "$bin" "$table" "$chain" "$match" "$tag" "$action"
        printf 'PostDown = %s -w -t %s -D %s %s %s %s 2>/dev/null || true\n' \
            "$bin" "$table" "$chain" "$match" "$tag" "$action"
    done < <(hub_firewall_rules)
}

# Canonical form of a config: no comments or formatting, peers keyed by public key, sorted
# AllowedIPs. Lines:
#   I<FS>key<FS>value         [Interface] setting
#   P<FS>pubkey<FS>key<FS>v   [Peer] setting
#   N<FS>pubkey<FS>name       peer name from "# peer: NAME", only with the second argument
#                             "names": names never take part in a comparison.
conf_canon() {
    [[ -f $1 ]] || return 0
    awk -v FS_SEP="$FS" -v NAMES="${2:-}" '
        function flush(   k) {
            if (pk == "") return
            for (k in pv) print "P" FS_SEP pk FS_SEP k FS_SEP pv[k]
            if (pname != "" && NAMES == "names") print "N" FS_SEP pk FS_SEP pname
        }
        function norm_list(v,   n, a, i, j, t, out) {
            gsub(/[ \t]/, "", v)
            n = split(v, a, ",")
            for (i = 1; i <= n; i++) for (j = i + 1; j <= n; j++) if (a[j] < a[i]) { t = a[i]; a[i] = a[j]; a[j] = t }
            out = ""
            for (i = 1; i <= n; i++) if (a[i] != "") out = out (out == "" ? "" : ",") a[i]
            return out
        }
        /^[ \t]*# peer: / { name = $0; sub(/^[ \t]*# peer: /, "", name); sub(/[ \t].*/, "", name); next }
        {
            line = $0
            sub(/#.*/, "", line)
            gsub(/^[ \t]+|[ \t]+$/, "", line)
            if (line == "") next
        }
        line ~ /^\[/ {
            if (sec == "peer") flush()
            sec = tolower(line) == "[peer]" ? "peer" : (tolower(line) == "[interface]" ? "iface" : "other")
            split("", pv); pk = ""; pname = (sec == "peer") ? name : ""; name = ""
            next
        }
        {
            k = line; sub(/[ \t]*=.*/, "", k); k = tolower(k)
            v = line; sub(/^[^=]*=[ \t]*/, "", v)
            if (sec == "iface") {
                if (k ~ /^(preup|postup|predown|postdown)$/) { hooks[k] = hooks[k] (hooks[k] == "" ? "" : " ; ") v; next }
                if (k == "address" || k == "dns") v = norm_list(((k in iface) ? iface[k] "," : "") v)
                iface[k] = v
            } else if (sec == "peer") {
                if (k == "publickey") { pk = v; next }
                if (k == "allowedips") v = norm_list((("allowedips" in pv) ? pv[k] "," : "") v)
                pv[k] = v
            }
        }
        END {
            if (sec == "peer") flush()
            for (k in iface) print "I" FS_SEP k FS_SEP iface[k]
            for (k in hooks) print "I" FS_SEP k FS_SEP hooks[k]
        }
    ' "$1" | LC_ALL=C sort
}
